package com.hamdi.tiktokcleaner

import java.util.Calendar
import java.util.TimeZone

/**
 * Pure deterministic account classifier and multi-locale date/username parser.
 * Upgraded in v2.0 with Eastern Arabic numeral support, smart year-rollover for MM-DD dates,
 * Arabic relative timestamps, and instant in-list row pre-classification.
 */
object Classifier {

    val GENERATED_USERNAME = Regex("^user\\d{6,}$", RegexOption.IGNORE_CASE)
    private val VALID_HANDLE = Regex("^[a-zA-Z0-9._]{2,32}$")
    private val RESERVED_WORDS = setOf(
        "following", "followers", "friends", "suggested", "live", "search",
        "profile", "inbox", "home", "discover", "shop", "messages", "activity"
    )

    private const val DAY_MS = 86_400_000L

    data class ClassificationResult(
        val category: Category,
        val detail: String
    )

    fun normalizeDigits(input: String): String {
        val sb = StringBuilder(input.length)
        for (ch in input) {
            when (ch) {
                in '٠'..'٩' -> sb.append((ch - '٠' + '0'.code).toChar())
                in '۰'..'۹' -> sb.append((ch - '۰' + '0'.code).toChar())
                else -> sb.append(ch)
            }
        }
        return sb.toString()
    }

    fun looksLikeUsername(text: String?): Boolean {
        if (text == null) return false
        val cleaned = text.trim().removePrefix("@").trim()
        if (cleaned.length < 2 || cleaned.length > 32) return false
        if (cleaned.lowercase() in RESERVED_WORDS) return false
        if (cleaned.all { it.isDigit() }) return false
        return VALID_HANDLE.matches(cleaned)
    }

    fun isAutoGeneratedHandle(username: String): Boolean {
        val cleaned = username.trim().removePrefix("@")
        return GENERATED_USERNAME.matches(cleaned)
    }

    fun classify(
        username: String,
        isGone: Boolean,
        isPrivate: Boolean,
        videoCount: Int?,
        lastPostTimestamp: Long?,
        currentTimestamp: Long,
        inactivityThresholdDays: Int
    ): ClassificationResult {
        val handle = username.trim().removePrefix("@")

        if (isGone) {
            return ClassificationResult(Category.GONE, "حساب محذوف أو غير موجود")
        }

        if (isPrivate) {
            if (isAutoGeneratedHandle(handle) && (videoCount == null || videoCount == 0)) {
                return ClassificationResult(Category.FAKE, "معرف افتراضي ($handle) وحساب خاص بدون نشاط")
            }
            return ClassificationResult(Category.UNKNOWN, "حساب خاص (لا يمكن قراءة الفيديوهات)")
        }

        if (videoCount != null && videoCount == 0) {
            return if (isAutoGeneratedHandle(handle)) {
                ClassificationResult(Category.FAKE, "معرف افتراضي ($handle) مع 0 فيديو")
            } else {
                ClassificationResult(Category.DEAD, "لا توجد فيديوهات منشورة (0 فيديو)")
            }
        }

        if (lastPostTimestamp != null && lastPostTimestamp > 0L) {
            val ageDays = ((currentTimestamp - lastPostTimestamp) / DAY_MS).toInt().coerceAtLeast(0)
            return if (ageDays >= inactivityThresholdDays) {
                ClassificationResult(
                    Category.DEAD,
                    "خامل منذ $ageDays يوم (الحد: $inactivityThresholdDays يوم)"
                )
            } else {
                ClassificationResult(
                    Category.ACTIVE,
                    "نشط (آخر فيديو منذ $ageDays يوم)"
                )
            }
        }

        if (videoCount != null && videoCount > 0) {
            return ClassificationResult(Category.ACTIVE, "حساب نشط ($videoCount فيديو)")
        }

        return ClassificationResult(Category.UNKNOWN, "تعذر قراءة بيانات الحساب من الواجهة")
    }

    /**
     * Instant zero-click pre-classification from the Following list row before opening a profile.
     * Returns a non-null ClassificationResult only when the row is 100% deterministically GONE.
     */
    fun preClassifyFromRow(
        username: String,
        rowTexts: List<String>
    ): ClassificationResult? {
        val combined = rowTexts.joinToString(" ").lowercase()
        val goneMarkers = listOf(
            "account not found",
            "user not found",
            "account banned",
            "حساب غير موجود",
            "المستخدم غير موجود",
            "تم حظر الحساب",
            "محذوف"
        )
        if (goneMarkers.any { combined.contains(it) }) {
            return ClassificationResult(Category.GONE, "حساب محذوف (تم كشفه مباشرة من القائمة)")
        }
        return null
    }

    /**
     * Parses TikTok video timestamps in English & Arabic:
     * - Relative: "2d", "2d ago", "3w", "5h", "10m", "منذ 3 أيام", "قبل أسبوعين", "أمس", "yesterday"
     * - Full ISO/Slash: "2023-05-14", "2023/5/14", "05-14-2023"
     * - Short month-day: "10-12", "5-3" (with automatic year rollover if date would fall in the future)
     */
    fun parseDateText(text: String?, nowMillis: Long): Long? {
        if (text == null) return null
        val norm = normalizeDigits(text).trim().lowercase()
        if (norm.isEmpty()) return null

        // Just now / today / yesterday
        if (norm == "just now" || norm == "now" || norm == "الآن" || norm == "اليوم" || norm == "today") {
            return nowMillis
        }
        if (norm == "yesterday" || norm == "أمس" || norm == "امس") {
            return nowMillis - DAY_MS
        }
        if (norm.contains("يومان") || norm.contains("يومين")) {
            return nowMillis - 2 * DAY_MS
        }
        if (norm.contains("أسبوعان") || norm.contains("أسبوعين") || norm.contains("اسبوعين")) {
            return nowMillis - 14 * DAY_MS
        }

        // English & Arabic relative units: e.g. "3d", "4w ago", "منذ 5 أيام", "5 ي"
        val relRegex = Regex("(?:منذ|قبل)?\\s*(\\d+)\\s*(s|sec|m|min|h|hr|d|day|days|w|wk|wks|mo|y|yr|ث|د|س|ي|يوم|أيام|ايام|أ|اسبوع|أسبوع|أسابيع|ش|شهر|سنة|سنوات)(?:\\s*ago)?")
        val relMatch = relRegex.find(norm)
        if (relMatch != null) {
            val amount = relMatch.groupValues[1].toLongOrNull() ?: return null
            val unit = relMatch.groupValues[2]
            val deltaMs = when (unit) {
                "s", "sec", "ث" -> amount * 1000L
                "m", "min", "د" -> amount * 60_000L
                "h", "hr", "س" -> amount * 3_600_000L
                "d", "day", "days", "ي", "يوم", "أيام", "ايام" -> amount * DAY_MS
                "w", "wk", "wks", "أ", "اسبوع", "أسبوع", "أسابيع" -> amount * 7L * DAY_MS
                "mo", "ش", "شهر" -> amount * 30L * DAY_MS
                "y", "yr", "سنة", "سنوات" -> amount * 365L * DAY_MS
                else -> return null
            }
            return nowMillis - deltaMs
        }

        // Full YYYY-MM-DD or YYYY/MM/DD
        val fullDateRegex = Regex("^(\\d{4})[-/.](\\d{1,2})[-/.](\\d{1,2})$")
        val fullMatch = fullDateRegex.find(norm)
        if (fullMatch != null) {
            val year = fullMatch.groupValues[1].toIntOrNull() ?: return null
            val month = fullMatch.groupValues[2].toIntOrNull() ?: return null
            val day = fullMatch.groupValues[3].toIntOrNull() ?: return null
            return buildUtcMillis(year, month, day)
        }

        // Short MM-DD or MM/DD (rolls back 1 year if the date in the current year is in the future)
        val shortDateRegex = Regex("^(\\d{1,2})[-/.](\\d{1,2})$")
        val shortMatch = shortDateRegex.find(norm)
        if (shortMatch != null) {
            val month = shortMatch.groupValues[1].toIntOrNull() ?: return null
            val day = shortMatch.groupValues[2].toIntOrNull() ?: return null
            val cal = Calendar.getInstance(TimeZone.getTimeZone("UTC")).apply {
                timeInMillis = nowMillis
            }
            var year = cal.get(Calendar.YEAR)
            var candidateMs = buildUtcMillis(year, month, day) ?: return null
            if (candidateMs > nowMillis + DAY_MS) {
                year -= 1
                candidateMs = buildUtcMillis(year, month, day) ?: return null
            }
            return candidateMs
        }

        return null
    }

    private fun buildUtcMillis(year: Int, month: Int, day: Int): Long? {
        if (year < 2014 || year > 2100) return null
        if (month !in 1..12 || day !in 1..31) return null
        val cal = Calendar.getInstance(TimeZone.getTimeZone("UTC"))
        cal.isLenient = false
        return try {
            cal.set(year, month - 1, day, 12, 0, 0)
            cal.set(Calendar.MILLISECOND, 0)
            cal.timeInMillis
        } catch (_: Exception) {
            null
        }
    }
}
